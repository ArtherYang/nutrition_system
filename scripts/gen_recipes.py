# ---------- 工具 ----------
def auto_kcal(ings):
    total = 0
    for n in ings:
        d = INDEX.get(n)
        if d and d.get("category") != "油脂":
            total += d["calories"] or 0
    return max(20, int(round(total)))


def auto_tags(ings, kcal):
    tags = []
    if any(n in PROTEIN for n in ings):
        tags.append("增肌")
    if kcal <= 140:
        tags.append("减脂")
    if not tags:
        tags.append("均衡")
    return tags


