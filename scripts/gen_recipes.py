recipes = []
seen = set()


def add(name, ings, flavor, region, method, tags=None, kcal=None, steps=None):
    if name in seen:
        return False
    ings = [i for i in dict.fromkeys(ings) if i in NAME_SET]
    if not ings:
        return False
    seen.add(name)
    if kcal is None:
        kcal = auto_kcal(ings)
    if tags is None:
        tags = auto_tags(ings, kcal)
    if steps is None:
        steps = steps_for(method, [i for i in ings if i not in SEASON])
    recipes.append({
        "name": name, "ingredients": ings, "steps": steps, "tags": tags,
        "flavor": flavor, "region": region,
        "estimated_calories": kcal, "method": method,
    })
    return True


