def kg_strip(s):
    """去掉 '名称: 数量' 中的数量，返回食材原始名。"""
    s = re.split(r"[：:]", s)[0]
    s = s.replace("　", " ").strip()
    return s


def kg_flavor(features):
    for x in features:
        if x.startswith("口味"):
            return x.split("：", 1)[-1].split(":", 1)[-1].strip()
    return "家常"


def kg_method(features):
    for x in features:
        if x.startswith("工艺"):
            raw = x.split("：", 1)[-1].split(":", 1)[-1].strip()
            return METHOD_MAP.get(raw, "煮")
    return "煮"


def kg_region(name):
    n = name
    if any(k in n for k in ["意大利", "意面", "意粉", "意式", "螺旋", "蝴蝶", "斜管",
                            "牛排", "沙拉", "罗勒", "奶油", "培根", "咖喱", "芝士"]):
        return "西式"
    if any(k in n for k in ["水煮", "鱼香", "麻婆", "麻辣", "辣子", "川味", "重庆",
                            "毛血旺", "红油", "香辣"]):
        return "川菜"
    if "糖醋" in n and "排骨" in n:
        return "浙菜"
    if "糖醋" in n and "鲤鱼" in n:
        return "鲁菜"
    if "本帮" in n or "上海" in n or "苏式" in n:
        return "苏菜"
    if "毛氏" in n:
        return "湘菜"
    if "广式" in n:
        return "粤菜"
    return "家常"


def kg_steps(raw_steps):
    out = []
    for s in raw_steps:
        s = re.sub(r"^\s*\d+\s*[:：.、]\s*", "", s)
        s = s.replace("　", " ").strip()
        if s:
            out.append(s)
    return out or ["按常规方法烹饪"]


with open(f"data_sources/cookbook_kg_entities.json", encoding="utf-8") as f:
    KG_DATA = json.load(f)

kg_imported = 0
kg_skipped = 0
for name, v in KG_DATA.items():
    clean = name.replace("(菜品)", "").strip()
    if not clean or "详解" in name or "步骤" in name or "(菜品)" in name:
        kg_skipped += 1
        continue
    ings = []
    for raw in v.get("主料", []) + v.get("辅料", []):
        raw = raw.replace("　", " ").strip()
        if not raw:
            continue
        token = kg_strip(raw)
        mapped = KG_MAP.get(token, token)
        if mapped and mapped in NAME_SET:
            ings.append(mapped)
    # 去重，且至少有一个非油脂真实主料
    ings = [i for i in dict.fromkeys(ings)]
    if not any(INDEX[i]["category"] != "油脂" for i in ings):
        kg_skipped += 1
        continue
    flavor = kg_flavor(v.get("特色", []))
    method = kg_method(v.get("特色", []))
    region = kg_region(clean)
    steps = kg_steps(v.get("制作步骤", []))
    if add(clean, ings, flavor, region, method, steps=steps):
        kg_imported += 1
    else:
        kg_skipped += 1

